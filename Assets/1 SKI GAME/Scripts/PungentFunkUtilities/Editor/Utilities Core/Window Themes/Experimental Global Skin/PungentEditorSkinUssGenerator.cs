        private static void AppendMappedFontBlock(StringBuilder builder, PungentEditorTextTarget target)
        {
            if (!PungentEditorTextRoleMap.GetApplyUss(target))
                return;

            string selectors = PungentEditorTextRoleMap.GetUssSelectors(target);
            if (string.IsNullOrWhiteSpace(selectors))
                return;

            AppendFontBlock(builder, selectors, PungentEditorTextRoleMap.GetTextRole(target));
        }

        private static void AppendFontBlock(StringBuilder builder, string selectors, UtilityWindowTheme.TextRole role)
        {
            string fontUrl = TryGetFontUrl(role.ToString());
            if (string.IsNullOrEmpty(fontUrl))
                return;
            builder.AppendLine($"{selectors} {{ -unity-font: {fontUrl}; }}");
        }

        private static string TryGetFontUrl(string roleName)
        {
            if (!TryParseTextRole(roleName, out UtilityWindowTheme.TextRole role))
                role = UtilityWindowTheme.TextRole.Body;

            Font font = UtilityWindowTheme.GetFont(role);
            if (font == null)
                return string.Empty;

            string assetPath = AssetDatabase.GetAssetPath(font);
            if (string.IsNullOrEmpty(assetPath))
                return string.Empty;

            return $"url(\"project://database/{assetPath}\")";
        }

        private static bool TryParseTextRole(string value, out UtilityWindowTheme.TextRole role)
        {
            if (string.IsNullOrEmpty(value))
            {
                role = UtilityWindowTheme.TextRole.Body;
                return false;
            }

            for (int i = 0; i < System.Enum.GetValues(typeof(UtilityWindowTheme.TextRole)).Length; i++)
            {
                UtilityWindowTheme.TextRole candidate = (UtilityWindowTheme.TextRole)i;
                if (string.Equals(candidate.ToString(), value, System.StringComparison.OrdinalIgnoreCase))
                {
                    role = candidate;
                    return true;
                }
            }

            role = UtilityWindowTheme.TextRole.Body;
            return false;
        }

        private static Color WithAlpha(Color color, float alphaMultiplier)
        {
            color.a = Mathf.Clamp01(color.a * Mathf.Clamp01(alphaMultiplier <= 0f ? 1f : alphaMultiplier));
            return color;
        }

        private static string ToRgba(Color color)
        {
            int r = Mathf.RoundToInt(Mathf.Clamp01(color.r) * 255f);
            int g = Mathf.RoundToInt(Mathf.Clamp01(color.g) * 255f);
            int b = Mathf.RoundToInt(Mathf.Clamp01(color.b) * 255f);
            string a = Mathf.Clamp01(color.a).ToString("0.###", CultureInfo.InvariantCulture);
            return $"rgba({r}, {g}, {b}, {a})";
        }

        private static string EscapeComment(string value)
        {
            return (value ?? string.Empty).Replace("*/", "* /");
        }
