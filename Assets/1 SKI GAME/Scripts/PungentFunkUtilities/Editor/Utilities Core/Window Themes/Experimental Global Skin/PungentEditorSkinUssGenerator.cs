        public static string BuildUss(PungentEditorSkinProfile profile, IEnumerable<PungentEditorStyleOverride> overrides, bool disabled)
        {
            var builder = new StringBuilder(8192);
            builder.AppendLine("/* <auto-generated> PungentFunk experimental Unity Editor skin bridge. */");
            builder.AppendLine("/* This file is generated from the Appearance Lab. Disable the bridge to restore an empty extension sheet. */");
            builder.AppendLine("/* It uses Unity editor USS extension selectors only; it does not patch editor resources or wrap IMGUI callbacks. */");
            builder.AppendLine("/* Raw preset readability should be judged with the bridge disabled. The bridge is a broader editor-theme preview and can shift apparent contrast inside the Appearance Lab itself. */");
            builder.AppendLine("/* Some Unity internals, especially script/asset preview implementations that stay in IMGUI or hidden native containers, may not expose stable USS hooks in every version. */");
            builder.AppendLine("/* Hierarchy note: if the left gutter/indent strip ignores all hierarchy USS selectors, that strip is likely drawn by Unity's IMGUI/native TreeView layer and needs session GUIStyle bridge coverage rather than generated USS. */");
            builder.AppendLine();

            if (disabled)
            {
                builder.AppendLine("/* Bridge disabled. No overrides emitted. */");
                return builder.ToString();
            }

            if (profile != null)
                builder.AppendLine($"/* Profile: {EscapeComment(profile.displayName)} | Base skin: {(EditorGUIUtility.isProSkin ? "Dark" : "Light")} */");

            int count = 0;
            foreach (PungentEditorStyleOverride item in overrides)
            {
                if (!item.EnabledByDefault || string.IsNullOrWhiteSpace(item.Selector))
                    continue;

                string property = ToUssProperty(item.Property);
                string value = ToUssValue(item);
                if (string.IsNullOrEmpty(property) || string.IsNullOrEmpty(value))
                    continue;

                builder.AppendLine($"{item.Selector} {{ {property}: {value}; }}");
                count++;
            }

            AppendSupplementalBlocks(builder);
            builder.AppendLine();
            builder.AppendLine($"/* Selectors emitted: {count} */");
            return builder.ToString();
        }

        private static string ToUssProperty(PungentEditorSkinProperty property)
        {
            switch (property)
            {
                case PungentEditorSkinProperty.Color:
                    return "color";
                case PungentEditorSkinProperty.BorderColor:
                    return "border-color";
                case PungentEditorSkinProperty.BorderWidth:
                    return "border-width";
                case PungentEditorSkinProperty.BorderRadius:
                    return "border-radius";
                case PungentEditorSkinProperty.UnityFont:
                    return "-unity-font";
                case PungentEditorSkinProperty.FontSize:
                    return "font-size";
                case PungentEditorSkinProperty.ImageTintColor:
                    return "-unity-background-image-tint-color";
                default:
                    return "background-color";
            }
        }

        private static string ToUssValue(PungentEditorStyleOverride item)
        {
            switch (item.Property)
            {
                case PungentEditorSkinProperty.BorderWidth:
                    return Mathf.Max(0, UtilityWindowTheme.PanelBorderWidth).ToString(CultureInfo.InvariantCulture) + "px";
                case PungentEditorSkinProperty.BorderRadius:
                    return Mathf.Max(0, UtilityWindowTheme.PanelCornerRadius).ToString(CultureInfo.InvariantCulture) + "px";
                case PungentEditorSkinProperty.UnityFont:
                    return TryGetFontUrl(item.ThemeRole);
                case PungentEditorSkinProperty.FontSize:
                    return Mathf.RoundToInt(12f * UtilityWindowTheme.TextScale).ToString(CultureInfo.InvariantCulture) + "px";
                case PungentEditorSkinProperty.ImageTintColor:
                    return ToRgba(WithAlpha(UtilityWindowTheme.GetColor(item.ThemeRole), item.AlphaMultiplier));
                default:
                    return ToRgba(WithAlpha(UtilityWindowTheme.GetColor(item.ThemeRole), item.AlphaMultiplier));
            }
        }

